@Composable fun ui(text: String): String {
    val context=LocalContext.current
    val language=LocalUiLanguage.current
    val labels=remember(context,language) {
        val config=Configuration(context.resources.configuration).apply { setLocale(Locale.forLanguageTag(language.ifBlank { "zh" })) }
        context.createConfigurationContext(config).resources.getStringArray(R.array.ui_labels)
    }
    val index=labelKeys.indexOf(text)
    if(index>=0) return labels[index]
    val patterns=remember { labelKeys.mapIndexedNotNull { i,key ->
        if(!key.contains("{0}")) null else i to Regex("^"+Regex.escape(key).replace(Regex("\\{[0-9]+\\}")) { "\\E(.*?)\\Q" }+"$",RegexOption.DOT_MATCHES_ALL)
    } }
    for((i,pattern) in patterns) {
        val match=pattern.matchEntire(text) ?: continue
        var result=labels[i]
        match.groupValues.drop(1).forEachIndexed { n,value -> result=result.replace("{$n}",value) }
        return result
    }
    return text
}
@Composable fun UiText(text: String, modifier: Modifier=Modifier, color: Color=Color.Unspecified,
    fontWeight: FontWeight?=null, maxLines: Int=Int.MAX_VALUE, style: TextStyle=LocalTextStyle.current) {
    androidx.compose.material3.Text(ui(text),modifier=modifier,color=color,fontWeight=fontWeight,maxLines=maxLines,style=style)
}

